# -*- coding: utf-8 -*-
"""
STEP B — train ONE shared Spectral-K3 + RQ-VAE-3layer model on Sports_and_Outdoors.

The audited trainer `analysis/mechanism/cross_tokenizer_shared/xt_train_shared.py` is
called **unchanged**, with the frozen recipe read off the historical run configuration:

    exposure    balanced        (every original instance once per factorization per epoch)
    seed        2025
    num_epochs  200
    batch_size  256
    infer_size  96
    lr          1e-4
    early_stop  10
    beam_size   30
    max_len     20
    capacity    4+4 layers, d_model 128, d_ff 1024, 6 heads, d_kv 64, dropout 0.1
    vocab       1027 with control tokens spectral_k3=1025, rqvae3=1026
    selection   macro-average item-level validation NDCG@20 across factorizations

The ONLY thing this wrapper changes is a single path: `xt_train_shared.sid_path` is
shadowed so that `spectral_k3` on Sports reads the K=3 array generated by
`sc_generate_sid.py` (under this round's output directory, because the artifact root is
read-only and holds no K=3 Sports array). Every other dataset and factorization resolves
exactly as before. No training logic, data logic or evaluation logic is reimplemented.

Usage
  python3 sc_train_shared.py --outdir outputs/sports_confirmation
"""
from __future__ import annotations

import os as _os
import pathlib as _pl
_REPO_ROOT = str(_pl.Path(__file__).resolve().parents[3])
_ART_ROOT = _os.environ.get('CFLA_ARTIFACT_ROOT') or _os.path.join(_REPO_ROOT, 'artifacts')
_UP_ROOT = _os.environ.get('CFLA_UPSTREAM_ROOT') or _ART_ROOT
import sys as _sys
if _REPO_ROOT not in _sys.path:
    _sys.path.insert(0, _REPO_ROOT)
from src.utils import repo_paths as rp  # noqa: E402
import argparse
import hashlib
import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[3]
XT = REPO / 'analysis' / 'mechanism' / 'cross_tokenizer_shared'
for p in (str(REPO), str(XT)):
    if p not in sys.path:
        sys.path.insert(0, p)

DATASET = 'Sports_and_Outdoors'
EXPECTED_CONTROL = {'spectral_k3': 1025, 'rqvae3': 1026}


def sha256_file(p):
    h = hashlib.sha256()
    with Path(p).open('rb') as f:
        for c in iter(lambda: f.read(1 << 20), b''):
            h.update(c)
    return h.hexdigest()


def resolve_sids(outdir):
    """spectral_k3 -> this round's generated K=3 array; rqvae3 -> the existing array."""
    gen = Path(outdir) / 'sid' / 'spectral_k3' / 'sid.npy'
    if not gen.exists():
        raise SystemExit(f'missing generated spectral_k3 SID: {gen}; run sc_generate_sid.py')
    return {
        'spectral_k3': gen.resolve(),
        'rqvae3': Path(_ART_ROOT + '/data') / DATASET /
                  f'{DATASET}_t5_rqvae.npy',
    }


def preflight(sids):
    """Assert the two factorizations are structurally comparable before training."""
    out = {}
    for f, p in sids.items():
        a = np.load(p, allow_pickle=True).astype(np.int64)
        if a.ndim != 2:
            raise SystemExit(f'{p} is not 2-D')
        injective = len({tuple(r) for r in a}) == len(a)
        if not injective:
            raise SystemExit(f'{p} is not injective')
        if a.shape[1] != 4:
            raise SystemExit(f'{p} has L={a.shape[1]}, expected 4')
        if a.min() < 0 or a.max() >= 256:
            raise SystemExit(f'{p} has codes outside [0,255]')
        out[f] = {'path': str(p), 'sha256': sha256_file(p), 'shape': list(a.shape),
                  'injective': True, 'codes_min': int(a.min()), 'codes_max': int(a.max())}
    if out['spectral_k3']['shape'] != out['rqvae3']['shape']:
        raise SystemExit('the two SID arrays differ in shape')
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--outdir', default='outputs/sports_confirmation')
    ap.add_argument('--seed', type=int, default=2025)
    ap.add_argument('--num_epochs', type=int, default=200)
    ap.add_argument('--device', default='cuda')
    a = ap.parse_args(argv)

    out = Path(a.outdir)
    sids = resolve_sids(out)
    info = preflight(sids)
    print('[preflight] SID arrays verified structurally comparable')
    for f, v in info.items():
        print(f'  {f:12s} shape={v["shape"]} injective={v["injective"]} '
              f'sha={v["sha256"][:16]}')

    cfg = {'dataset': DATASET, 'factorizations': 'spectral_k3:rqvae3',
           'exposure': 'balanced', 'seed': a.seed, 'num_epochs': a.num_epochs,
           'batch_size': 256, 'infer_size': 96, 'lr': 1e-4, 'early_stop': 10,
           'beam_size': 30, 'max_len': 20,
           'capacity': {'num_layers': 4, 'num_decoder_layers': 4, 'd_model': 128,
                        'd_ff': 1024, 'num_heads': 6, 'd_kv': 64, 'dropout_rate': 0.1},
           'selection': 'macro-average item-level validation NDCG@20 across factorizations'}
    cfg_hash = hashlib.sha256(json.dumps(cfg, sort_keys=True).encode()).hexdigest()[:8]
    run_id = f'sports_shared_spec3_rqvae3_seed{a.seed}_{cfg_hash}'
    run_dir = out / 'runs' / run_id
    if run_dir.exists():
        raise SystemExit(f'HARD FAIL: {run_dir} already exists')
    run_dir.mkdir(parents=True)

    (run_dir / 'config.json').write_text(json.dumps(cfg, indent=2))
    # PRE_RUN manifest: every input this run consumes
    pre = []
    for f, v in info.items():
        pre.append(f'{v["sha256"]}  {v["path"]}')
    emb = Path(_ART_ROOT + '/data') / DATASET / 'item_emb.parquet'
    pre.append(f'{sha256_file(emb)}  {emb}')
    for s in ('train', 'valid', 'test'):
        pq = Path(_ART_ROOT + '/data') / DATASET / f'{s}.parquet'
        pre.append(f'{sha256_file(pq)}  {pq}')
    for f in ('xt_train_shared.py', 'xt_common.py'):
        pre.append(f'{sha256_file(XT/f)}  {XT/f}')
    pre.append(f'{sha256_file(Path(__file__))}  {Path(__file__)}')
    (run_dir / 'PRE_RUN_ARTIFACT_MANIFEST.sha256').write_text('\n'.join(pre) + '\n')
    (run_dir / 'RUN_METADATA.json').write_text(json.dumps({
        'run_id': run_id, 'dataset': DATASET, 'config': cfg, 'config_hash': cfg_hash,
        'sids': info, 'seed': a.seed,
        'git_sha': subprocess.run(['git', 'rev-parse', 'HEAD'], capture_output=True,
                                  text=True, cwd=str(REPO)).stdout.strip(),
        'trainer': 'xt_train_shared.main (audited, called unchanged)',
        'sid_path_override': {'spectral_k3': str(sids['spectral_k3']),
                              'reason': 'artifact root holds no K=3 Sports array and is '
                                        'read-only; this round writes under '
                                        'outputs/sports_confirmation/'},
        'test_used_for_selection': False,
        'started': time.strftime('%Y-%m-%dT%H:%M:%S%z'),
    }, indent=2, default=str))

    # ---- shadow exactly one path, then call the audited trainer unchanged ----
    import xt_common
    import xt_train_shared

    _orig_sid_path = xt_common.sid_path

    def scoped_sid_path(tok, ds):
        if ds == DATASET and tok in sids:
            return sids[tok]
        return _orig_sid_path(tok, ds)

    xt_train_shared.sid_path = scoped_sid_path

    ckpt = run_dir / 'shared_model.pt'
    argv_in = ['--dataset', DATASET, '--factorizations', 'spectral_k3:rqvae3',
               '--save', str(ckpt), '--log', str(run_dir / 'train.log'),
               '--run_dir', str(run_dir), '--seed', str(a.seed),
               '--num_epochs', str(a.num_epochs), '--exposure', 'balanced',
               '--device', a.device]
    print(f'[train] run_id={run_id}')
    print(f'[train] calling xt_train_shared.main({argv_in})')
    rc = xt_train_shared.main(argv_in)

    if ckpt.exists():
        (run_dir / 'checkpoint.sha256').write_text(sha256_file(ckpt) + '\n')
    status = 'completed' if rc == 0 and ckpt.exists() else 'failed'
    (run_dir / 'status.json').write_text(json.dumps({
        'run_id': run_id, 'status': status, 'return_code': rc,
        'finished': time.strftime('%Y-%m-%dT%H:%M:%S%z')}, indent=2))
    shots = [p for p in sorted(run_dir.rglob('*')) if p.is_file()
             and p.name != 'POST_RUN_ARTIFACT_MANIFEST.sha256']
    (run_dir / 'POST_RUN_ARTIFACT_MANIFEST.sha256').write_text(
        '\n'.join(f'{sha256_file(p)}  {p}' for p in shots) + '\n')
    print(f'[train] status={status} -> {run_dir}')
    return 0 if status == 'completed' else 1


if __name__ == '__main__':
    sys.exit(main())
