#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate `SELECTOR_FEATURE_AUDIT.md` from the actual declared feature lists.

The table is produced from the same `feature_names()` function the dataset builder
uses, so the audit cannot drift from the features that were really computed.  Any
feature that could depend on the target is rejected by an explicit assertion.

Run:
  python3 af_feature_audit.py --selectordir <selector dir>
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from af_build_selector_dataset import (CROSS_FEATURES, FACTORIZATIONS, HIST_FEATURES,  # noqa: E402
                                       feature_names, per_factor_feature_names)

DESC = {
    'top1_prob': 'probability of the highest-probability merged item in this '
                 'factorization\'s beam (softmax over the 30 beam scores)',
    'top2_prob': 'probability of the second-highest merged item',
    'top1_top2_margin': 'top1_prob − top2_prob (decision confidence)',
    'beam_entropy': 'Shannon entropy of the beam probability distribution',
    'mass_top5': 'total probability mass of the 5 highest-probability merged items',
    'mass_top10': 'total probability mass of the 10 highest-probability merged items',
    'mass_top20': 'total probability mass of the 20 highest-probability merged items',
    'beam_score_mean': 'mean length-normalised beam log-probability',
    'beam_score_std': 'standard deviation of the beam log-probabilities',
    'n_unique_items': 'number of distinct item ids among the valid beams',
    'collapse_ratio': 'valid beams / distinct items (beam→item collapse)',
    'valid_sid_ratio': 'fraction of the 30 beams that decode to a valid item id',
}

CROSS_DESC = {
    'x_top20_jaccard': 'Jaccard similarity of the two factorizations\' top-20 item sets',
    'x_top20_intersection': 'size of the intersection of the two top-20 item sets',
    'x_top20_union': 'size of the union of the two top-20 item sets',
    'x_top1_item_agreement': '1 if both factorizations rank the same item first',
    'x_rank_corr_common': 'Spearman correlation of the two rankings restricted to '
                          'items present in both candidate sets',
    'x_prob_mass_l1': 'L1 distance between the two probability mass functions over '
                      'the union of candidate items',
}

HIST_DESC = {
    'hist_len_mean': 'number of non-pad history tokens (canonical max_len truncation)',
    'hist_len_max': 'identical to hist_len_mean; retained for a stable schema',
    'hist_len_F1_minus_F2': 'identically 0: history length is a property of the '
                            'parquet row, not of the factorization',
}

REPO = HERE.parents[2]


def row(name, dim, source, infer):
    return (f'| `{name}` | {dim} | {source} | {infer} | NO | NO |')


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--selectordir', required=True)
    a = ap.parse_args(argv)
    sel = Path(a.selectordir)
    names_h, names_p = feature_names()

    # ---- hard rejection rule: no feature may be target-derived ----
    banned = ('target', 'nll', 'rank', 'utility', 'user_id', 'uid', 'label')
    offenders = [n for n in names_h + names_p
                 if any(b in n.lower() for b in ('nll', 'user_id', 'target', 'utility', 'q1', 'q2'))]
    if offenders:
        raise SystemExit(f'REJECTED: feature names suggesting target dependency: {offenders}')

    lines = []
    lines.append('# SELECTOR_FEATURE_AUDIT.md')
    lines.append('')
    lines.append('Audit of every input feature of the two router families. Generated by '
                 '`analysis/mechanism/adaptive_factorization/af_feature_audit.py` from the '
                 'same `feature_names()` declaration the dataset builder uses, so this table '
                 'cannot drift from the features actually computed.')
    lines.append('')
    lines.append('## Hard rules')
    lines.append('')
    lines.append('* `uses target` is **NO** for every row: no feature is a function of the '
                 'ground-truth item, its SID, its beam rank, or its teacher-forced NLL.')
    lines.append('* `uses test labels` is **NO** for every row: features on the test split are '
                 'computed from frozen-model beam outputs and the user history only.')
    lines.append('* No user id is a feature. User identity is used only to define the '
                 'RouterTrain/RouterDev/RouterHoldout split and the seen/unseen-user report.')
    lines.append('* The label `q_m` and the secondary label `q_NLL = softmax(-TotalNLL)` are '
                 '**supervision**, not features. They are constructed from the *validation* '
                 'target, which is known at router-training time, and never appear in X.')
    lines.append('* Every feature is available before any target interaction at inference: '
                 'the history is always known, and beam statistics are computed **before** any '
                 'target is consulted (the generation call never receives the target).')
    lines.append('')
    lines.append('## Router H — history-only')
    lines.append('')
    lines.append('Routable **before** beam generation. It requires the encoder pass under both '
                 'factorizations but no decoding.')
    lines.append('')
    lines.append('| feature | dim | source | available at inference? | uses target? | uses test labels? |')
    lines.append('|---|---|---|---|---|---|')
    for i in range(128):
        lines.append(row(f'h_F1_{i}', 1, 'mean over non-pad final encoder hidden states of the '
                                         'F1-tokenised history (frozen shared encoder)', 'YES'))
    for i in range(128):
        lines.append(row(f'h_F2_{i}', 1, 'mean over non-pad final encoder hidden states of the '
                                         'F2-tokenised history (frozen shared encoder)', 'YES'))
    for i in range(128):
        lines.append(row(f'h_absdiff_{i}', 1, '|h_F1 − h_F2| per dimension: how much the two '
                                              'tokenisations move the frozen representation', 'YES'))
    for n in HIST_FEATURES:
        lines.append(row(n, 1, HIST_DESC[n], 'YES'))
    lines.append('')
    lines.append(f'**Router H input dimension: {len(names_h)}** (3x128 encoder features + '
                 f'{len(HIST_FEATURES)} history-length features).')
    lines.append('')
    lines.append('## Router P — prediction-aware')
    lines.append('')
    lines.append('Sees target-free beam statistics from **both** factorizations, plus the Router H '
                 'history block. Because it needs both beams it does **not** save generation '
                 'compute; it is the adaptive-fusion candidate.')
    lines.append('')
    lines.append('| feature | dim | source | available at inference? | uses target? | uses test labels? |')
    lines.append('|---|---|---|---|---|---|')
    for f in FACTORIZATIONS:
        for n in per_factor_feature_names(f):
            base = n[len(f) + 1:]
            lines.append(row(n, 1, f'{DESC[base]} — from the frozen shared model\'s '
                                   f'{f} beam dump', 'YES'))
    for n in CROSS_FEATURES:
        lines.append(row(n, 1, CROSS_DESC[n], 'YES'))
    for n in HIST_FEATURES:
        lines.append(row(n, 1, HIST_DESC[n], 'YES'))
    lines.append('')
    lines.append(f'**Router P input dimension: {len(names_p)}** '
                 f'({len(FACTORIZATIONS)}x{len(per_factor_feature_names(FACTORIZATIONS[0]))} '
                 f'beam features + {len(CROSS_FEATURES)} cross-factorization features + '
                 f'{len(HIST_FEATURES)} history-length features).')
    lines.append('')
    lines.append('The compact candidate arrays `cand_ids1/cand_p1/cand_ids2/cand_p2` are stored '
                 'alongside the features so that any per-user weight vector can be scored '
                 'exactly. They are **candidate sets and probabilities only** — they contain no '
                 'target information.')
    lines.append('')
    lines.append('## Explicitly excluded quantities')
    lines.append('')
    lines.append('| quantity | why excluded |')
    lines.append('|---|---|')
    lines.append('| teacher-forced target TotalNLL | requires the target; used only as a '
                 'secondary training label and as a post-freeze diagnostic |')
    lines.append('| target item id / target SID / target embedding | unavailable at inference |')
    lines.append('| target rank `r_m` and utility `U_m` | the labels themselves |')
    lines.append('| `q_m`, `q_NLL` | labels, not features |')
    lines.append('| user id | identity shortcut; forbidden by the protocol |')
    lines.append('| test-split statistics of any kind | the test split is not read until after '
                 'the freeze manifest is written |')
    lines.append('')
    lines.append('## Feature normalisation')
    lines.append('')
    lines.append('Mean/std are fitted on **RouterTrain rows only** and applied unchanged to '
                 'RouterDev, RouterHoldout and Test. The scaler is stored in '
                 '`scalers/router_h_scaler.npz` and `scalers/router_p_scaler.npz` and its hash is '
                 'recorded in `SELECTOR_FREEZE_MANIFEST.json`.')
    lines.append('')
    lines.append('## Annotation completeness')
    lines.append('')
    lines.append(f'* Router H: {len(names_h)} features declared and audited.')
    lines.append(f'* Router P: {len(names_p)} features declared and audited.')
    lines.append('* Feature-name scan for target/eval-derived tokens: '
                 f'{"PASS (no offender)" if not offenders else "FAIL"}.')

    out = REPO / 'outputs' / 'adaptive_factorization' / 'selector' / 'SELECTOR_FEATURE_AUDIT.md'
    out.write_text('\n'.join(lines) + '\n')
    print(f'wrote {out} ({len(names_h)} H features, {len(names_p)} P features)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
